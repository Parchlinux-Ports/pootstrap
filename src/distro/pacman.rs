use crate::config::Config;
use crate::error::{PootstrapError, Result};
use crate::isolation::PrivilegedRunner;
use crate::profile::device::Architecture;
use std::fs;
use std::path::Path;

pub struct PacmanManager;

impl PacmanManager {
    pub fn generate_pacman_conf(
        config: &Config,
        arch: Architecture,
        target_file: &Path,
    ) -> Result<()> {
        let conf_content = format!(
            r#"# Generated by pootstrap for Parch Linux Mobile
[options]
Architecture = {arch}
HoldPkg = pacman glibc
CheckSpace
SigLevel = Never
LocalFileSigLevel = Optional

# Parch Mobile Repository
[parch-mobile]
SigLevel = Never
Server = {parch_mirror}/$repo/$arch

# Arch Linux ARM Repositories
[core]
SigLevel = Never
Server = {alarm_mirror}

[extra]
SigLevel = Never
Server = {alarm_mirror}

[alarm]
SigLevel = Never
Server = {alarm_mirror}
"#,
            arch = arch.as_str(),
            parch_mirror = config.parch_mirror,
            alarm_mirror = config.alarm_mirror,
        );

        if let Some(parent) = target_file.parent() {
            let _ = fs::create_dir_all(parent).or_else(|_| PrivilegedRunner::create_dir_all(parent));
        }

        if fs::write(target_file, &conf_content).is_err() {
            PrivilegedRunner::write_file(target_file, &conf_content)?;
        }
        Ok(())
    }

    pub fn run_pacstrap(
        pacman_conf: &Path,
        cache_dir: &Path,
        rootfs: &Path,
        packages: &[String],
    ) -> Result<()> {
        let pkg_cache = cache_dir.join("pacman").join("pkg");
        if fs::create_dir_all(&pkg_cache).is_err() {
            PrivilegedRunner::create_dir_all(&pkg_cache)?;
        }

        which::which("pacstrap").map_err(|_| PootstrapError::MissingTool {
            tool: "pacstrap (from arch-install-scripts)".into(),
        })?;

        let mut cmd = PrivilegedRunner::command("pacstrap");
        cmd.arg("-C")
            .arg(pacman_conf)
            .arg("-c")
            .arg("-M")
            .arg("-d")
            .arg(rootfs);

        for pkg in packages {
            cmd.arg(pkg);
        }

        tracing::info!("Executing pacstrap for {} packages...", packages.len());
        let status = cmd.status().map_err(PootstrapError::Io)?;

        if !status.success() {
            return Err(PootstrapError::RootfsBuild(format!(
                "pacstrap failed with exit code: {:?}",
                status.code()
            )));
        }

        Ok(())
    }
}
